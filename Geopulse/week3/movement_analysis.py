ROOT = Path.cwd()
# Corrected to point to the available local file
SOURCE = ROOT / "gps_pings.csv"
OUT = ROOT / "outputs/week3/member1_movement"
OUT.mkdir(parents=True, exist_ok=True)

REQUIRED = ["PingID", "DeviceID", "SessionID", "Timestamp",
            "Longitude", "Latitude", "SpeedKmh", "MovementMode"]

def project_to_utm(df):
    # Dynamically project Lon/Lat to UTM (Zone 32N as a standard default, or auto-determined)
    # We will use WGS84 UTM Zone 32N (EPSG:32632) as a standard metric projection
    wgs84 = pyproj.CRS("EPSG:4326")
    # Automatically estimate UTM zone from the median longitude to keep it accurate
    med_lon = df["Longitude"].median()
    zone = int((med_lon + 180) / 6) + 1
    lat_val = df["Latitude"].median()
    hemisphere = 32600 if lat_val >= 0 else 32700
    utm_epsg = hemisphere + zone

    proj_utm = pyproj.Transformer.from_crs(wgs84, pyproj.CRS(f"EPSG:{utm_epsg}"), always_xy=True)
    utm_x, utm_y = proj_utm.transform(df["Longitude"].values, df["Latitude"].values)
    df["UTM_X"] = utm_x
    df["UTM_Y"] = utm_y
    return df

def main():
    if not SOURCE.exists():
        raise FileNotFoundError(f"Missing {SOURCE}; please ensure gps_pings.csv is in the workspace.")
    original = pd.read_csv(SOURCE)
    missing = [c for c in REQUIRED if c not in original.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    df = original.copy()
    df["Timestamp"] = pd.to_datetime(df["Timestamp"], errors="coerce")
    for c in ["Longitude", "Latitude", "SpeedKmh"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=["DeviceID", "SessionID", "Timestamp", "Longitude", "Latitude"])

    # Project to metric UTM coordinates for displacement calculations
    df = project_to_utm(df)

    df = df.sort_values(["DeviceID", "SessionID", "Timestamp"]).copy()

    grp = df.groupby(["DeviceID", "SessionID"], sort=False)
    prev_x, prev_y = grp["UTM_X"].shift(), grp["UTM_Y"].shift()
    prev_time = grp["Timestamp"].shift()
    df["SegmentDistanceMeters"] = np.hypot(df["UTM_X"] - prev_x, df["UTM_Y"] - prev_y).fillna(0)
    df["PingGapMinutes"] = (df["Timestamp"] - prev_time).dt.total_seconds() / 60

    df["AnomalyReason"] = ""
    df.loc[df["SpeedKmh"] < 0, "AnomalyReason"] += "Negative speed;"
    df.loc[df["SpeedKmh"] > 160, "AnomalyReason"] += "Speed above 160 km/h;"
    df.loc[df["PingGapMinutes"] > 60, "AnomalyReason"] += "Gap above 60 minutes;"
    df.loc[df["PingGapMinutes"] < 0, "AnomalyReason"] += "Negative time gap;"
    df.loc[df["SegmentDistanceMeters"] > 10000, "AnomalyReason"] += "Displacement above 10 km;"
    df["IsAnomaly"] = df["AnomalyReason"].ne("")

    device = df.groupby("DeviceID").agg(
        TotalPings=("PingID", "count"), SessionCount=("SessionID", "nunique"),
        EstimatedDistanceMeters=("SegmentDistanceMeters", "sum"),
        AverageRecordedSpeedKmh=("SpeedKmh", "mean"),
        MaximumRecordedSpeedKmh=("SpeedKmh", "max"),
        FirstPing=("Timestamp", "min"), LastPing=("Timestamp", "max"),
        AnomalyCount=("IsAnomaly", "sum")).reset_index()
    device["EstimatedDistanceKm"] = device["EstimatedDistanceMeters"] / 1000
    device["ObservedSpanMinutes"] = (device["LastPing"] - device["FirstPing"]).dt.total_seconds() / 60

    session = df.groupby(["DeviceID", "SessionID"]).agg(
        TotalPings=("PingID", "count"),
        EstimatedDistanceMeters=("SegmentDistanceMeters", "sum"),
        AverageRecordedSpeedKmh=("SpeedKmh", "mean"),
        MaximumRecordedSpeedKmh=("SpeedKmh", "max"),
        FirstPing=("Timestamp", "min"), LastPing=("Timestamp", "max"),
        AnomalyCount=("IsAnomaly", "sum")).reset_index()
    session["EstimatedDistanceKm"] = session["EstimatedDistanceMeters"] / 1000
    session["ObservedSpanMinutes"] = (session["LastPing"] - session["FirstPing"]).dt.total_seconds() / 60

    mode = df.groupby("MovementMode", dropna=False).agg(
        TotalPings=("PingID", "count"), UniqueDevices=("DeviceID", "nunique"),
        AverageRecordedSpeedKmh=("SpeedKmh", "mean"),
        MaximumRecordedSpeedKmh=("SpeedKmh", "max"),
        EstimatedDistanceMeters=("SegmentDistanceMeters", "sum")).reset_index()

    df.to_csv(OUT / "movement_ping_level_metrics.csv", index=False)
    device.to_csv(OUT / "device_movement_summary.csv", index=False)
    session.to_csv(OUT / "session_movement_summary.csv", index=False)
    mode.to_csv(OUT / "movement_mode_summary.csv", index=False)
    df.loc[df["IsAnomaly"]].to_csv(OUT / "gps_anomalies.csv", index=False)

    report = pd.DataFrame([
        ("Input rows", len(original)), ("Analysed rows", len(df)),
        ("Unique devices", df["DeviceID"].nunique()),
        ("Unique sessions", df["SessionID"].nunique()),
        ("Anomalous rows", int(df["IsAnomaly"].sum())),
        ("Estimated displacement km", round(df["SegmentDistanceMeters"].sum()/1000, 3))
    ], columns=["Metric", "Value"])
    report.to_csv(OUT / "movement_analysis_report.csv", index=False)
    print(report.to_string(index=False))
    print(f"Saved outputs to {OUT.resolve()}")

if __name__ == "__main__":
    main()