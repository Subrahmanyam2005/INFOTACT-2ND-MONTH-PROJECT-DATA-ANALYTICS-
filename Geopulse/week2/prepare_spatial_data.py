import pandas as pd
import numpy as np

from pathlib import Path
from pyproj import Transformer


# ============================================================
# 1. PROJECT CONFIGURATION
# ============================================================

# Google Colab working directory
PROJECT_DIR = Path("/content")

# Input files
GPS_FILE = PROJECT_DIR / "gps_pings.csv"
STORE_FILE = PROJECT_DIR / "stores.csv"

# Output directory
OUTPUT_DIR = (
    PROJECT_DIR / "outputs" / "week2" / "member1"
)

# Create output folder automatically
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Simulated Visakhapatnam coordinate boundaries
MIN_LAT = 17.6468
MAX_LAT = 17.7268

MIN_LON = 83.1785
MAX_LON = 83.2585

# Coordinate reference systems
SOURCE_CRS = "EPSG:4326"
TARGET_CRS = "EPSG:32644"


# ============================================================
# 2. REQUIRED COLUMNS
# ============================================================

GPS_REQUIRED_COLUMNS = [
    "PingID",
    "DeviceID",
    "SessionID",
    "Latitude",
    "Longitude",
    "Timestamp"
]

STORE_REQUIRED_COLUMNS = [
    "StoreID",
    "StoreName",
    "StoreCategory",
    "Latitude",
    "Longitude"
]


# ============================================================
# 3. CREATE OUTPUT FOLDER
# ============================================================

def create_folders():

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print("Output folder ready:")
    print(OUTPUT_DIR)


# ============================================================
# 4. CHECK INPUT FILES
# ============================================================

def check_files():

    print("\nChecking input files...")

    if not GPS_FILE.exists():
        raise FileNotFoundError(
            f"GPS file not found: {GPS_FILE}"
        )

    if not STORE_FILE.exists():
        raise FileNotFoundError(
            f"Store file not found: {STORE_FILE}"
        )

    print("GPS file found:", GPS_FILE.name)
    print("Store file found:", STORE_FILE.name)


# ============================================================
# 5. READ DATASETS
# ============================================================

def read_datasets():

    print("\nReading datasets...")

    gps_df = pd.read_csv(GPS_FILE)
    stores_df = pd.read_csv(STORE_FILE)

    print("GPS records:", len(gps_df))
    print("Store records:", len(stores_df))

    print("\nGPS columns:")
    print(gps_df.columns.tolist())

    print("\nStore columns:")
    print(stores_df.columns.tolist())

    return gps_df, stores_df


# ============================================================
# 6. CHECK REQUIRED COLUMNS
# ============================================================

def check_columns(gps_df, stores_df):

    missing_gps = [
        col for col in GPS_REQUIRED_COLUMNS
        if col not in gps_df.columns
    ]

    missing_stores = [
        col for col in STORE_REQUIRED_COLUMNS
        if col not in stores_df.columns
    ]

    if missing_gps:
        raise ValueError(
            f"Missing GPS columns: {missing_gps}"
        )

    if missing_stores:
        raise ValueError(
            f"Missing store columns: {missing_stores}"
        )

    print("\nRequired columns verified successfully.")


# ============================================================
# 7. VALIDATE GPS DATA
# ============================================================

def validate_gps(gps_df):

    print("\nValidating GPS records...")

    gps_df = gps_df.copy()

    # Convert coordinates to numeric values
    gps_df["Latitude"] = pd.to_numeric(
        gps_df["Latitude"], errors="coerce"
    )

    gps_df["Longitude"] = pd.to_numeric(
        gps_df["Longitude"], errors="coerce"
    )

    # Convert timestamps
    gps_df["Timestamp"] = pd.to_datetime(
        gps_df["Timestamp"], errors="coerce"
    )

    # Check missing values
    missing_coordinates = (
        gps_df["Latitude"].isna()
        | gps_df["Longitude"].isna()
    )

    # Check invalid coordinate ranges
    invalid_coordinates = (
        ~gps_df["Latitude"].between(-90, 90)
        | ~gps_df["Longitude"].between(-180, 180)
    )

    # Check simulated project-area boundaries
    outside_project_area = (
        ~gps_df["Latitude"].between(MIN_LAT, MAX_LAT)
        | ~gps_df["Longitude"].between(MIN_LON, MAX_LON)
    )

    # Check invalid timestamps
    invalid_timestamps = gps_df["Timestamp"].isna()

    # Combine validation conditions
    invalid_mask = (
        missing_coordinates
        | invalid_coordinates
        | outside_project_area
        | invalid_timestamps
    )

    gps_rejected = gps_df[invalid_mask].copy()
    gps_valid = gps_df[~invalid_mask].copy()

    # Identify duplicate PingIDs
    duplicate_mask = gps_valid.duplicated(
        subset=["PingID"],
        keep="first"
    )

    gps_duplicates = gps_valid[duplicate_mask].copy()

    # Remove duplicate records from prepared dataset
    gps_clean = gps_valid[~duplicate_mask].copy()

    print("Original GPS records:", len(gps_df))
    print("Rejected GPS records:", len(gps_rejected))
    print("Duplicate GPS records:", len(gps_duplicates))
    print("Valid GPS records:", len(gps_clean))

    return gps_clean, gps_rejected, gps_duplicates


# ============================================================
# 8. VALIDATE STORE DATA
# ============================================================

def validate_stores(stores_df):

    print("\nValidating store records...")

    stores_df = stores_df.copy()

    stores_df["Latitude"] = pd.to_numeric(
        stores_df["Latitude"], errors="coerce"
    )

    stores_df["Longitude"] = pd.to_numeric(
        stores_df["Longitude"], errors="coerce"
    )

    missing_coordinates = (
        stores_df["Latitude"].isna()
        | stores_df["Longitude"].isna()
    )

    invalid_coordinates = (
        ~stores_df["Latitude"].between(-90, 90)
        | ~stores_df["Longitude"].between(-180, 180)
    )

    outside_project_area = (
        ~stores_df["Latitude"].between(MIN_LAT, MAX_LAT)
        | ~stores_df["Longitude"].between(MIN_LON, MAX_LON)
    )

    missing_ids = stores_df["StoreID"].isna()

    invalid_mask = (
        missing_coordinates
        | invalid_coordinates
        | outside_project_area
        | missing_ids
    )

    stores_rejected = stores_df[invalid_mask].copy()
    stores_valid = stores_df[~invalid_mask].copy()

    # Identify duplicate StoreIDs
    duplicate_mask = stores_valid.duplicated(
        subset=["StoreID"],
        keep="first"
    )

    stores_duplicates = stores_valid[duplicate_mask].copy()

    stores_clean = stores_valid[~duplicate_mask].copy()

    print("Original stores:", len(stores_df))
    print("Rejected stores:", len(stores_rejected))
    print("Duplicate stores:", len(stores_duplicates))
    print("Valid stores:", len(stores_clean))

    return stores_clean, stores_rejected, stores_duplicates


# ============================================================
# 9. CREATE PROJECTED GEOMETRIES
# ============================================================

def add_projected_geometry(df):

    print("\nCreating projected geometries...")

    df = df.copy()

    # Initialize transformer inside the function
    transformer = Transformer.from_crs(
        SOURCE_CRS,
        TARGET_CRS,
        always_xy=True
    )

    # Convert longitude and latitude into UTM coordinates
    x, y = transformer.transform(
        df["Longitude"].to_numpy(),
        df["Latitude"].to_numpy()
    )

    # Store projected coordinates in metres
    df["UTM_X"] = x
    df["UTM_Y"] = y

    # Create WKT point geometry
    df["geom_wkt"] = [
        f"POINT ({x_coord:.3f} {y_coord:.3f})"
        for x_coord, y_coord in zip(x, y)
    ]

    print("Projected geometries created successfully.")

    return df


# ============================================================
# 10. SAVE CSV OUTPUTS
# ============================================================

def save_csv(df, filename):

    output_path = OUTPUT_DIR / filename

    df.to_csv(
        output_path,
        index=False
    )

    print("Saved:", output_path.name)

    return output_path


# ============================================================
# 11. GENERATE PREPARATION SUMMARY
# ============================================================

def create_summary(
    gps_original,
    stores_original,
    gps_clean,
    gps_rejected,
    gps_duplicates,
    stores_clean,
    stores_rejected,
    stores_duplicates
):

    summary = pd.DataFrame({

        "Metric": [
            "Original GPS Records",
            "Valid GPS Records",
            "Rejected GPS Records",
            "Duplicate GPS Records",
            "Original Store Records",
            "Valid Store Records",
            "Rejected Store Records",
            "Duplicate Store Records"
        ],

        "Count": [
            len(gps_original),
            len(gps_clean),
            len(gps_rejected),
            len(gps_duplicates),
            len(stores_original),
            len(stores_clean),
            len(stores_rejected),
            len(stores_duplicates)
        ]

    })

    save_csv(
        summary,
        "preparation_summary.csv"
    )

    print("\nPREPARATION SUMMARY")
    print(summary.to_string(index=False))


# ============================================================
# 12. MAIN PROGRAM
# ============================================================

def main():

    print("=" * 60)
    print("GEOPULSE - WEEK 2 SPATIAL DATA PREPARATION")
    print("MEMBER 1")
    print("=" * 60)

    # Step 1: Create folders
    create_folders()

    # Step 2: Check input files
    check_files()

    # Step 3: Read datasets
    gps_original, stores_original = read_datasets()

    # Step 4: Check columns
    check_columns(gps_original, stores_original)

    # Step 5: Validate GPS data
    gps_clean, gps_rejected, gps_duplicates = (
        validate_gps(gps_original)
    )

    # Step 6: Validate store data
    stores_clean, stores_rejected, stores_duplicates = (
        validate_stores(stores_original)
    )

    # Stop if there is no valid data
    if gps_clean.empty:
        raise ValueError(
            "No valid GPS records remain after validation."
        )

    if stores_clean.empty:
        raise ValueError(
            "No valid store records remain after validation."
        )

    # Step 7: Create projected GPS geometries
    gps_prepared = add_projected_geometry(gps_clean)

    # Step 8: Create projected store geometries
    stores_prepared = add_projected_geometry(stores_clean)

    # Step 9: Save prepared datasets
    save_csv(
        gps_prepared,
        "gps_points_utm.csv"
    )

    save_csv(
        stores_prepared,
        "store_points_utm.csv"
    )

    # Step 10: Save rejected and duplicate records
    save_csv(
        gps_rejected,
        "gps_rejected.csv"
    )

    save_csv(
        gps_duplicates,
        "gps_duplicates.csv"
    )

    save_csv(
        stores_rejected,
        "stores_rejected.csv"
    )

    save_csv(
        stores_duplicates,
        "stores_duplicates.csv"
    )

    # Step 11: Generate summary
    create_summary(
        gps_original,
        stores_original,
        gps_clean,
        gps_rejected,
        gps_duplicates,
        stores_clean,
        stores_rejected,
        stores_duplicates
    )

    print("\n" + "=" * 60)
    print("WEEK 2 MEMBER 1 TASK COMPLETED")
    print("=" * 60)

    print("\nAll output files are saved in:")
    print(OUTPUT_DIR)


# ============================================================
# 13. RUN PROGRAM
# ============================================================

main()