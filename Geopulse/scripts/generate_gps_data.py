# 3. GENERATE GPS MOBILITY DATASET
# ==================================================

def generate_gps_data(stores):

    if GPS_FILE.exists():
        GPS_FILE.unlink()

    store_lat = stores["Latitude"].to_numpy()
    store_lon = stores["Longitude"].to_numpy()

    ping_numbers = np.arange(PINGS_PER_DEVICE)

    total_records = 0

    start = pd.Timestamp(START_DATE)

    for batch_start in range(
        0, NUM_DEVICES, CHUNK_SIZE
    ):

        batch_end = min(
            batch_start + CHUNK_SIZE,
            NUM_DEVICES
        )

        n = batch_end - batch_start

        # ------------------------------------------
        # DEVICE INFORMATION
        # ------------------------------------------

        device_ids = np.array([
            f"DEV{i:06d}"
            for i in range(batch_start + 1, batch_end + 1)
        ])

        session_ids = np.array([
            f"SES{i:06d}"
            for i in range(batch_start + 1, batch_end + 1)
        ])

        device_types = rng.choice(
            ["Android", "iOS"],
            n,
            p=[0.75, 0.25]
        )

        # ------------------------------------------
        # INITIAL DEVICE LOCATIONS
        # ------------------------------------------

        lat = rng.uniform(
            CENTER_LAT - 0.025,
            CENTER_LAT + 0.025,
            n
        )

        lon = rng.uniform(
            CENTER_LON - 0.025,
            CENTER_LON + 0.025,
            n
        )

        # ------------------------------------------
        # DISTRIBUTE DEVICES ACROSS 7 DAYS
        # ------------------------------------------

        start_days = rng.integers(0, 7, n)

        start_minutes = rng.integers(
            6 * 60, 18 * 60, n
        )

        # Calculate timedelta on a flattened array to prevent pandas dimensional TypeErrors
        delta_minutes = (
            start_days[:, None] * 1440
            + start_minutes[:, None]
            + ping_numbers[None, :] * PING_INTERVAL_MINUTES
        ).ravel()

        timestamps = (
            start
            + pd.to_timedelta(delta_minutes, unit="m")
        ).values.reshape(n, PINGS_PER_DEVICE)

        # ------------------------------------------
        # MOVEMENT MODE AND SPEED
        # ------------------------------------------

        movement_modes = rng.choice(
            [
                "Walking",
                "Driving",
                "Cycling",
                "Stationary"
            ],
            size=(n, PINGS_PER_DEVICE),
            p=[0.40, 0.30, 0.10, 0.20]
        )

        speed_ranges = {
            "Walking": (2, 6),
            "Driving": (15, 40),
            "Cycling": (8, 20),
            "Stationary": (0, 0.5)
        }

        speeds = np.zeros(
            (n, PINGS_PER_DEVICE)
        )

        for mode, limits in speed_ranges.items():

            mask = movement_modes == mode

            speeds[mask] = rng.uniform(
                limits[0],
                limits[1],
                mask.sum()
            )

        # ------------------------------------------
        # HEADING
        # ------------------------------------------

        heading = np.zeros(
            (n, PINGS_PER_DEVICE)
        )

        heading[:, 0] = rng.uniform(0, 360, n)

        for j in range(1, PINGS_PER_DEVICE):

            heading[:, j] = (
                heading[:, j - 1]
                + rng.normal(0, 25, n)
            ) % 360

        # ------------------------------------------
        # MOVEMENT SIMULATION
        # ------------------------------------------

        distance_km = (
            speeds * PING_INTERVAL_MINUTES / 60
        )

        angle = np.deg2rad(heading)

        latitude_history = np.empty(
            (n, PINGS_PER_DEVICE)
        )

        longitude_history = np.empty(
            (n, PINGS_PER_DEVICE)
        )

        for j in range(PINGS_PER_DEVICE):

            lat += (
                distance_km[:, j]
                * np.cos(angle[:, j]) / 111
            )

            lon += (
                distance_km[:, j]
                * np.sin(angle[:, j])
                / (
                    111 * np.cos(
                        np.deg2rad(lat)
                    )
                )
            )

            lat = np.clip(lat, LAT_MIN, LAT_MAX)
            lon = np.clip(lon, LON_MIN, LON_MAX)

            latitude_history[:, j] = lat
            longitude_history[:, j] = lon

        # ------------------------------------------
        # FLATTEN DATA
        # ------------------------------------------

        lat_flat = latitude_history.ravel()
        lon_flat = longitude_history.ravel()

        timestamp_flat = timestamps.ravel()

        speed_flat = speeds.ravel().round(2)

        heading_flat = heading.ravel().round(2)

        movement_flat = movement_modes.ravel()

        total = n * PINGS_PER_DEVICE

        # ------------------------------------------
        # GPS ACCURACY AND ALTITUDE
        # ------------------------------------------

        accuracy = rng.uniform(
            5, 35, total
        ).round(2)

        altitude = rng.uniform(
            5, 100, total
        ).round(2)

        # ------------------------------------------
        # DISTANCE TO NEAREST STORE
        # ------------------------------------------

        distance_matrix = np.sqrt(
            (
                (lat_flat[:, None] -
                 store_lat[None, :]) * 111
            ) ** 2
            +
            (
                (lon_flat[:, None] -
                 store_lon[None, :])
                * 111
                * np.cos(np.deg2rad(CENTER_LAT))
            ) ** 2
        )

        nearest_distance = distance_matrix.min(axis=1)

        location_types = rng.choice(
            [
                "Residential",
                "Road",
                "Public Area"
            ],
            total,
            p=[0.45, 0.35, 0.20]
        )

        location_types[
            nearest_distance <= 0.5
        ] = "Commercial"

        # ------------------------------------------
        # DATE AND TIME ATTRIBUTES
        # ------------------------------------------

        time_index = pd.DatetimeIndex(timestamp_flat)

        event_dates = time_index.date

        hour_of_day = time_index.hour

        day_of_week = time_index.day_name()

        is_weekend = time_index.dayofweek >= 5

        # ------------------------------------------
        # UNIQUE PING IDENTIFIERS
        # ------------------------------------------

        ping_ids = [
            f"PING{i:09d}"
            for i in range(
                total_records + 1,
                total_records + total + 1
            )
        ]

        # ------------------------------------------
        # CREATE FINAL DATAFRAME
        # ------------------------------------------

        df = pd.DataFrame({

            "PingID": ping_ids,

            "DeviceID": np.repeat(
                device_ids,
                PINGS_PER_DEVICE
            ),

            "SessionID": np.repeat(
                session_ids,
                PINGS_PER_DEVICE
            ),

            "Latitude": lat_flat.round(6),

            "Longitude": lon_flat.round(6),

            "Timestamp": timestamp_flat,

            "AccuracyMeters": accuracy,

            "SpeedKmh": speed_flat,

            "HeadingDegrees": heading_flat,

            "AltitudeMeters": altitude,

            "DeviceType": np.repeat(
                device_types,
                PINGS_PER_DEVICE
            ),

            "MovementMode": movement_flat,

            "LocationType": location_types,

            "EventDate": event_dates,

            "HourOfDay": hour_of_day,

            "DayOfWeek": day_of_week,

            "IsWeekend": is_weekend,

            "DataSource": "SYNTHETIC_GPS"

        })

        # ------------------------------------------
        # SAVE DATA IN CHUNKS
        # ------------------------------------------

        df.to_csv(
            GPS_FILE,
            mode="a",
            header=(total_records == 0),
            index=False
        )

        total_records += len(df)

        print(
            f"Generated {total_records:,} / "
            f"{NUM_DEVICES * PINGS_PER_DEVICE:,}"
        )

        del df

    print("\nGPS dataset successfully generated!")

    print("Total GPS records:", total_records)


