import numpy as np
import pandas as pd
from pathlib import Path

# ==================================================
# 1. PROJECT CONFIGURATION
# ==================================================

NUM_DEVICES = 1000
PINGS_PER_DEVICE = 100
NUM_STORES = 20

CHUNK_SIZE = 100

START_DATE = "2026-11-02"
PING_INTERVAL_MINUTES = 5

RANDOM_SEED = 42
rng = np.random.default_rng(RANDOM_SEED)

# Simulated Visakhapatnam city boundaries
CENTER_LAT = 17.6868
CENTER_LON = 83.2185

LAT_MIN = 17.6468
LAT_MAX = 17.7268

LON_MIN = 83.1785
LON_MAX = 83.2585

# Project folders
# Replaced Path(__file__) with Path.cwd() to work in Google Colab
ROOT = Path.cwd()
DATA_DIR = ROOT / "data"

DATA_DIR.mkdir(parents=True, exist_ok=True)

GPS_FILE = DATA_DIR / "gps_pings.csv"
STORE_FILE = DATA_DIR / "stores.csv"


# ==================================================
# 2. GENERATE RETAIL STORE DATASET
# ==================================================

