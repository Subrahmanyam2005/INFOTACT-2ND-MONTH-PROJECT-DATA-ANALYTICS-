# 5. CHECK REQUIRED COLUMNS
# ============================================================

def check_required_columns(df, required_columns, dataset_name):

    missing_columns = [
        col for col in required_columns
        if col not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"{dataset_name} is missing columns: "
            f"{missing_columns}"
        )

    print(f"{dataset_name}: Required columns verified.")


# ============================================================
# 6. PREPARE NUMERIC COLUMNS
# ============================================================

def convert_numeric_columns(df):

    df = df.copy()

    numeric_columns = [
        "Latitude",
        "Longitude",
        "UTM_X",
        "UTM_Y"
    ]

    for column in numeric_columns:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )

    return df


# ============================================================
# 7. VALIDATE SPATIAL DATA
# ============================================================

def validate_dataset(df, dataset_type):

    print(f"\nValidating {dataset_type} spatial data...")

    df = convert_numeric_columns(df)

    result = df.copy()

    # --------------------------------------------------------
    # Check 1: Missing values
    # --------------------------------------------------------

    result["Check_Missing_Values"] = (
        ~result[
            ["Latitude", "Longitude", "UTM_X", "UTM_Y", "geom_wkt"]
        ].isna().any(axis=1)
    )

    # --------------------------------------------------------
    # Check 2: Geographic coordinate validity
    # --------------------------------------------------------

    geographic_valid = (
        result["Latitude"].between(-90, 90)
        & result["Longitude"].between(-180, 180)
    )

    result["Check_Geographic_Range"] = geographic_valid

    # --------------------------------------------------------
    # Check 3: Project boundary validation
    # --------------------------------------------------------

    inside_project_area = (
        result["Latitude"].between(MIN_LAT, MAX_LAT)
        & result["Longitude"].between(MIN_LON, MAX_LON)
    )

    result["Check_Project_Boundary"] = inside_project_area

    # --------------------------------------------------------
    # Check 4: UTM coordinate validity
    # --------------------------------------------------------

    utm_valid = (
        np.isfinite(result["UTM_X"])
        & np.isfinite(result["UTM_Y"])
        & (result["UTM_X" ] > 0)
        & (result["UTM_Y"] > 0)
    )

    result["Check_UTM_Coordinates"] = utm_valid

    # --------------------------------------------------------
    # Check 5: Duplicate ID validation
    # --------------------------------------------------------

    if dataset_type == "GPS":

        id_column = "PingID"

    else:

        id_column = "StoreID"

    result["Check_Unique_ID"] = (
        result[id_column].notna()
        & ~result[id_column].duplicated(keep=False)
    )

    # --------------------------------------------------------
    # Check 6: WKT geometry validation
    # --------------------------------------------------------

    expected_wkt = (
        "POINT ("
        + result["UTM_X"].map(
            lambda value: (
                f"{value:.3f}" if pd.notna(value) else "nan"
            )
        )
        + " "
        + result["UTM_Y"].map(
            lambda value: (
                f"{value:.3f}" if pd.notna(value) else "nan"
            )
        )
        + ")"
    )

    result["Check_WKT_Geometry"] = (
        result["geom_wkt"].astype("string").str.strip()
        == expected_wkt.astype("string")
    )

    # --------------------------------------------------------
    # Check 7: Recalculate UTM coordinates
    # --------------------------------------------------------

    transformer = Transformer.from_crs(
        SOURCE_CRS,
        TARGET_CRS,
        always_xy=True
    )

    expected_x = np.full(len(result), np.nan)
    expected_y = np.full(len(result), np.nan)

    coordinate_mask = (
        result["Longitude"].notna()
        & result["Latitude"].notna()
        & result["Longitude"].between(-180, 180)
        & result["Latitude"].between(-90, 90)
    )

    if coordinate_mask.any():

        x, y = transformer.transform(
            result.loc[
                coordinate_mask, "Longitude"
            ].to_numpy(),

            result.loc[
                coordinate_mask, "Latitude"
            ].to_numpy()
        )

        expected_x[coordinate_mask.to_numpy()] = x
        expected_y[coordinate_mask.to_numpy()] = y

    result["Check_UTM_Transformation"] = (
        np.isfinite(expected_x)
        & np.isfinite(expected_y)
        & np.isclose(
            result["UTM_X"].to_numpy(),
            expected_x,
            atol=UTM_TOLERANCE_METRES,
            rtol=0,
            equal_nan=False
        )
        & np.isclose(
            result["UTM_Y"].to_numpy(),
            expected_y,
            atol=UTM_TOLERANCE_METRES,
            rtol=0,
            equal_nan=False
        )
    )

    # --------------------------------------------------------
    # Additional GPS timestamp validation
    # --------------------------------------------------------

    if dataset_type == "GPS":

        parsed_timestamp = pd.to_datetime(
            result["Timestamp"],
            errors="coerce"
        )

        result["Check_Timestamp"] = (
            parsed_timestamp.notna()
        )

    # --------------------------------------------------------
    # Final validation status
    # --------------------------------------------------------

    check_columns = [
        "Check_Missing_Values",
        "Check_Geographic_Range",
        "Check_Project_Boundary",
        "Check_UTM_Coordinates",
        "Check_Unique_ID",
        "Check_WKT_Geometry",
        "Check_UTM_Transformation"
    ]

    if dataset_type == "GPS":

        check_columns.append("Check_Timestamp")

    result["ValidationStatus"] = np.where(
        result[check_columns].all(axis=1),
        "PASS",
        "FAIL"
    )

    # Record reasons for failures
    def get_failure_reasons(row):

        failed_checks = [
            column.replace("Check_", "")
            for column in check_columns
            if not bool(row[column])
        ]

        return ", ".join(failed_checks)

    result["ValidationIssues"] = result.apply(
        get_failure_reasons,
        axis=1
    )

    passed = (
        result["ValidationStatus"] == "PASS"
    ).sum()

    failed = (
        result["ValidationStatus"] == "FAIL"
    ).sum()

    print("Total records:", len(result))
    print("Passed records:", passed)
    print("Failed records:", failed)

    return result


