def main():

    print("=" * 65)
    print("GEOPULSE - SPATIAL DATA VALIDATION")
    print("WEEK 2 - MEMBER 1")
    print("=" * 65)

    # Step 1: Check prepared files
    check_input_files()

    # Step 2: Load datasets
    gps_df, stores_df = load_data()

    # Step 3: Check required columns
    check_required_columns(
        gps_df,
        GPS_REQUIRED,
        "GPS dataset"
    )

    check_required_columns(
        stores_df,
        STORE_REQUIRED,
        "Store dataset"
    )

    # Step 4: Validate GPS dataset
    gps_result = validate_dataset(
        gps_df,
        "GPS"
    )

    # Step 5: Validate store dataset
    store_result = validate_dataset(
        stores_df,
        "STORES"
    )

    # Step 6: Save detailed validation results
    save_validation_results(
        gps_result,
        store_result
    )

    # Step 7: Create summary
    create_validation_summary(
        gps_result,
        store_result
    )

    # Step 8: Final status
    gps_pass = (
        gps_result["ValidationStatus"] == "PASS"
    ).all()

    store_pass = (
        store_result["ValidationStatus"] == "PASS"
    ).all()

    print("\n" + "=" * 65)

    if gps_pass and store_pass:

        print("SPATIAL VALIDATION COMPLETED.")
        print("All GPS and store records passed.")

    else:

        print("SPATIAL VALIDATION COMPLETED WITH FAILURES.")
        print("Check the failed-record CSV files.")

    print("=" * 65)

    print("\nOutput folder:")
    print(OUTPUT_DIR)


# ============================================================
# 11. EXECUTE PROGRAM
# ============================================================

main()