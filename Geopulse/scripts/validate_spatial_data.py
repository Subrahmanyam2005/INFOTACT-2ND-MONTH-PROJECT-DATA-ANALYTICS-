import pandas as pd
import numpy as np

from pathlib import Path
from pyproj import Transformer


# ============================================================
# 1. PROJECT CONFIGURATION
# ============================================================

PROJECT_DIR = Path("/content")

OUTPUT_DIR = (
    PROJECT_DIR / "outputs" / "week2" / "member1"
)

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Pointing to the actual locations of the prepared files in /content
GPS_FILE = PROJECT_DIR / "gps_pings.csv"
STORE_FILE = PROJECT_DIR / "store_points_utm.csv"

# Simulated Visakhapatnam boundaries
MIN_LAT = 17.6468
MAX_LAT = 17.7268

MIN_LON = 83.1785
MAX_LON = 83.2585

SOURCE_CRS = "EPSG:4326"
TARGET_CRS = "EPSG:32644"

# Allow small floating-point differences in UTM coordinates
UTM_TOLERANCE_METRES = 0.01


# ============================================================
# 2. REQUIRED COLUMNS
# ============================================================

GPS_REQUIRED = [
    "PingID",
    "DeviceID",
    "SessionID",
    "Latitude",
    "Longitude",
    "Timestamp",
    "UTM_X",
    "UTM_Y",
    "geom_wkt"
]

STORE_REQUIRED = [
    "StoreID",
    "StoreName",
    "StoreCategory",
    "Latitude",
    "Longitude",
    "UTM_X",
    "UTM_Y",
    "geom_wkt"
]


# ============================================================
# 3. CHECK INPUT FILES
# ============================================================

def check_input_files():

    print("\nChecking prepared spatial datasets...")

    if not GPS_FILE.exists():
        raise FileNotFoundError(
            f"GPS prepared file not found: {GPS_FILE}\n"
            "Run prepare_spatial_data.py first."
        )

    if not STORE_FILE.exists():
        raise FileNotFoundError(
            f"Store prepared file not found: {STORE_FILE}\n"
            "Run prepare_spatial_data.py first."
        )

    print("GPS prepared file found.")
    print("Store prepared file found.")


# ============================================================
# 4. LOAD PREPARED DATA WITH DYNAMIC PREPARATION IF MISSING
# ============================================================

def load_data():

    print("\nLoading prepared datasets...")

    gps_df = pd.read_csv(GPS_FILE)
    stores_df = pd.read_csv(STORE_FILE)

    # Dynamically project and prepare GPS data if the UTM coordinates are missing
    if "UTM_X" not in gps_df.columns or "UTM_Y" not in gps_df.columns or "geom_wkt" not in gps_df.columns:
        print("GPS columns 'UTM_X', 'UTM_Y', or 'geom_wkt' missing. Projecting coordinates...")
        transformer = Transformer.from_crs(SOURCE_CRS, TARGET_CRS, always_xy=True)

        # Initialize projected coordinate arrays
        xs = np.full(len(gps_df), np.nan)
        ys = np.full(len(gps_df), np.nan)

        valid_coords = gps_df["Longitude"].notna() & gps_df["Latitude"].notna()
        if valid_coords.any():
            transformed_x, transformed_y = transformer.transform(
                gps_df.loc[valid_coords, "Longitude"].to_numpy(),
                gps_df.loc[valid_coords, "Latitude"].to_numpy()
            )
            xs[valid_coords] = transformed_x
            ys[valid_coords] = transformed_y

        gps_df["UTM_X"] = xs
        gps_df["UTM_Y"] = ys
        gps_df["geom_wkt"] = gps_df.apply(
            lambda row: f"POINT ({row['UTM_X']:.3f} {row['UTM_Y']:.3f})" if pd.notna(row['UTM_X']) else np.nan,
            axis=1
        )

    print("GPS records:", len(gps_df))
    print("Store records:", len(stores_df))

    return gps_df, stores_df


