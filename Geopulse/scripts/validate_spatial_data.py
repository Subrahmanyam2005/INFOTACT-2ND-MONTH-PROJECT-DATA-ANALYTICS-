# 9. SAVE VALIDATION RESULTS
# ============================================================

def save_validation_results(gps_result, store_result):

    print("\nSaving validation results...")

    gps_result.to_csv(
        OUTPUT_DIR / "gps_spatial_validation.csv",
        index=False
    )

    store_result.to_csv(
        OUTPUT_DIR / "store_spatial_validation.csv",
        index=False
    )

    # Save only failed GPS records
    gps_failed = gps_result[
        gps_result["ValidationStatus"] == "FAIL"
    ]

    gps_failed.to_csv(
        OUTPUT_DIR / "gps_spatial_validation_failed.csv",
        index=False
    )

    # Save only failed store records
    stores_failed = store_result[
        store_result["ValidationStatus"] == "FAIL"
    ]

    stores_failed.to_csv(
        OUTPUT_DIR / "store_spatial_validation_failed.csv",
        index=False
    )

    print("All validation files saved successfully.")


