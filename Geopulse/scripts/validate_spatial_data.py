# 8. CREATE VALIDATION SUMMARY
# ============================================================

def create_validation_summary(gps_result, store_result):

    print("\nCreating validation summary...")

    datasets = {
        "GPS": gps_result,
        "Stores": store_result
    }

    summary_rows = []

    for dataset_name, df in datasets.items():

        checks = [
            col for col in df.columns
            if col.startswith("Check_")
        ]

        for check in checks:

            passed = int(df[check].sum())
            failed = int(len(df) - passed)

            summary_rows.append({
                "Dataset": dataset_name,
                "Validation_Check": check,
                "Total_Records": len(df),
                "Passed": passed,
                "Failed": failed,
                "Pass_Percentage": round(
                    (passed / len(df) * 100)
                    if len(df) > 0 else 0,
                    2
                )
            })

        summary_rows.append({
            "Dataset": dataset_name,
            "Validation_Check": "OVERALL",
            "Total_Records": len(df),
            "Passed": int(
                (df["ValidationStatus"] == "PASS").sum()
            ),
            "Failed": int(
                (df["ValidationStatus" ] == "FAIL").sum()
            ),
            "Pass_Percentage": round(
                (
                    (df["ValidationStatus"] == "PASS").sum()
                    / len(df) * 100
                ) if len(df) > 0 else 0,
                2
            )
        })

    summary_df = pd.DataFrame(summary_rows)

    summary_path = (
        OUTPUT_DIR / "spatial_validation_summary.csv"
    )

    summary_df.to_csv(
        summary_path,
        index=False
    )

    print("\nVALIDATION SUMMARY")
    print(summary_df.to_string(index=False))

    print("\nSummary saved:", summary_path.name)

    return summary_df


